// Regenerates THIRD-PARTY-NOTICES.md from the installed production dependencies (the packages
// bundled into dist/). Run after changing dependencies: `npm run notices`.
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const tree = JSON.parse(
  execFileSync('npm', ['ls', '--omit=dev', '--all', '--json'], { encoding: 'utf8' }),
)

const found = new Map()
;(function walk(deps = {}) {
  for (const [name, info] of Object.entries(deps)) {
    if (!info.version || found.has(name)) continue
    found.set(name, info.version)
    walk(info.dependencies)
  }
})(tree.dependencies)

const sections = [...found.keys()].sort().map((name) => {
  const dir = join('node_modules', name)
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const file = existsSync(dir) && readdirSync(dir).find((f) => /^licen[cs]e/i.test(f))
  const text = file ? readFileSync(join(dir, file), 'utf8').trim() : '(no licence file shipped)'
  return `## ${name} ${pkg.version}\n\nLicence: ${pkg.license}\n\n\`\`\`text\n${text}\n\`\`\`\n`
})

writeFileSync(
  'THIRD-PARTY-NOTICES.md',
  `# Third-party notices

AI Integration Review includes the following third-party software in its production build. Each
package is used under its own licence, reproduced below. These licences are separate from, and not
replaced by, the licences that apply to this project's original code and content.

This file is generated by \`scripts/third-party-notices.mjs\`; do not edit it by hand.

${sections.join('\n')}`,
)
console.log(`Wrote notices for ${found.size} packages.`)
